import { fireEvent, render, screen, within } from '@testing-library/react';
import { expect, it, vi } from 'vitest';
import DemoShareEditor from './DemoShareEditor';
import { sandboxFixture } from './test/fixtures';
import { reviseDraft, saveDraft, seedDraft } from './demo-builder';

it('demonstrates saving, receiver-only access, denial for other members and revocation without fetch', () => {
  const network = vi.spyOn(globalThis, 'fetch');
  const sandbox = { ...sandboxFixture, id: 'share-ui', name: '経営管理の共有見本', template_id: 'management-dashboard' as const, status: 'running' as const };
  const draft = seedDraft(sandbox.id, sandbox.template_id);
  saveDraft(sandbox.id, reviseDraft(draft, 'タイトルを「共有する経営画面」に変更'));
  const onSaved = vi.fn();
  render(<DemoShareEditor sandbox={sandbox} onSaved={onSaved} />);
  expect(screen.getByRole('button', { name: '共有設定を保存' })).toBeDisabled();
  fireEvent.click(screen.getByRole('checkbox', { name: /メンバーA/ }));
  fireEvent.click(screen.getByRole('button', { name: '共有先の画面を見る' }));
  expect(screen.getByTestId('demo-recipient-view')).toHaveTextContent('このメンバーには共有されていません');
  fireEvent.click(screen.getByRole('button', { name: '所有者の設定' }));
  fireEvent.click(screen.getByRole('button', { name: '共有設定を保存' }));
  expect(onSaved).toHaveBeenCalledTimes(1);
  fireEvent.click(screen.getByRole('button', { name: '共有先の画面' }));
  const recipient = within(screen.getByTestId('demo-recipient-view'));
  expect(recipient.getByRole('heading', { name: '共有する経営画面' })).toBeInTheDocument();
  expect(recipient.getByText('閲覧のみ')).toBeInTheDocument();
  for (const name of ['起動', '停止', '削除', '指示を反映', '共有設定']) expect(recipient.queryByRole('button', { name })).not.toBeInTheDocument();
  fireEvent.change(screen.getByLabelText('画面を確認するメンバー（デモ）'), { target: { value: 'member-b' } });
  expect(recipient.queryByTestId('demo-canvas')).not.toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: '所有者の設定' }));
  fireEvent.click(screen.getByRole('checkbox', { name: /メンバーA/ }));
  fireEvent.click(screen.getByRole('button', { name: '共有設定を保存' }));
  fireEvent.click(screen.getByRole('button', { name: '共有先の画面' }));
  fireEvent.change(screen.getByLabelText('画面を確認するメンバー（デモ）'), { target: { value: 'member-a' } });
  const revoked = within(screen.getByTestId('demo-recipient-view'));
  expect(revoked.getByText('このメンバーには共有されていません')).toBeInTheDocument();
  expect(revoked.queryByTestId('demo-canvas')).not.toBeInTheDocument();
  expect(network).not.toHaveBeenCalled();
});

it('retains saved settings on reopen and removes the preview when the app stops/deletes', () => {
  const sandbox = { ...sandboxFixture, id: 'share-state-ui', status: 'running' as const };
  const props = { sandbox, onSaved: vi.fn() };
  const first = render(<DemoShareEditor {...props} />);
  fireEvent.click(screen.getByRole('checkbox', { name: /メンバーA/ }));
  fireEvent.click(screen.getByRole('button', { name: '共有設定を保存' }));
  first.unmount();
  const second = render(<DemoShareEditor {...props} />);
  expect(screen.getByRole('checkbox', { name: /メンバーA/ })).toBeChecked();
  fireEvent.click(screen.getByRole('button', { name: '共有先の画面' }));
  expect(screen.getByTestId('demo-canvas')).toBeInTheDocument();
  second.rerender(<DemoShareEditor {...props} sandbox={{ ...sandbox, status: 'stopping' }} />);
  expect(screen.queryByTestId('demo-canvas')).not.toBeInTheDocument();
  expect(screen.getByText('アプリを停止処理中です')).toBeInTheDocument();
  second.rerender(<DemoShareEditor {...props} sandbox={{ ...sandbox, status: 'stopped' }} />);
  expect(screen.queryByTestId('demo-canvas')).not.toBeInTheDocument();
  expect(screen.getByText('アプリは停止中です')).toBeInTheDocument();
  second.rerender(<DemoShareEditor {...props} sandbox={{ ...sandbox, desired_state: 'deleted', status: 'deleting' }} />);
  expect(screen.getByText('アプリを削除処理中です')).toBeInTheDocument();
  expect(screen.queryByText('このアプリは削除されました')).not.toBeInTheDocument();
  second.rerender(<DemoShareEditor {...props} sandbox={{ ...sandbox, desired_state: 'deleted', status: 'failed' }} />);
  expect(screen.getByText('アプリの状態を確認してください')).toBeInTheDocument();
  expect(screen.queryByText('アプリを削除処理中です')).not.toBeInTheDocument();
  second.rerender(<DemoShareEditor {...props} sandbox={{ ...sandbox, desired_state: 'deleted', status: 'deleted' }} />);
  expect(screen.getByText('このアプリは削除されました')).toBeInTheDocument();
});
